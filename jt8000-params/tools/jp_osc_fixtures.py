#!/usr/bin/env python3
# =============================================================================
# jp_osc_fixtures.py — measured JP-8000 OSC1 SHAPE fixtures for the host tests
# =============================================================================
#
# ROLE
#   Reads the calibrated JE-8086 Ctrl1-ramp captures (6-pass sweep files,
#   2026-10-22) and writes test/JpOsc1Fixtures.h: complex harmonics h1..h40 of
#   the JP waveform at 9 knob positions, for SAW (JvSAW), TRI (JvTRI) and
#   TRIANGLE MOD (JTRIM).  The host tests render OscCore and compare against
#   these with a shift- and gain-invariant waveform error, so the firmware is
#   pinned to the MEASUREMENT, not to its own previous output.
#
# METHOD (same as the analysis in project doc osc-shapes/jp-osc1-capture-
# analysis-2026-10-22.md)
#   * f0 pinned (130.8132 Hz — Live C2 played by the JE an octave up,
#     phase-stable to 0.0001 Hz across every pass).
#   * Pass 1 of each file = Ctrl1 ramp, Ctrl2 = 0.  Knob law calibrated from
#     the square's PW ramp: knob(t) = (t − T0)/(T1 − T0), T0 −1.318 s,
#     T1 40.93 s from note-on.
#   * Exact-f0 DFT over 4-cycle Hann windows, rotated to the ABSOLUTE
#     oscillator phase (all windows coherent), averaged over 0.15 s centred
#     on the knob position.  Harmonic amplitudes are in capture units; the
#     test removes gain and phase origin, so only the SHAPE is pinned.
#
# USAGE
#   python tools/jp_osc_fixtures.py --dir <folder with the three WAVs> \
#          --out ../test/JpOsc1Fixtures.h
#
# © 2026 Kris Bishop — MIT licensed.
# =============================================================================
import argparse
import os
import numpy as np
from scipy.io import wavfile

F0 = 130.8132
T0, T1 = -1.318, 40.93
KNOBS = [0.04, 0.125, 0.25, 0.375, 0.5, 0.625, 0.75, 0.875, 1.0]
H = 40
WAVES = [('Saw', 'saw_full_jp.wav'), ('Tri', 'tri_jp.wav'), ('TriMod', 'tri_mod_jp.wav')]


def load(path):
    sr, x = wavfile.read(path)
    x = x.astype(np.float64)
    if x.ndim > 1:
        x = x.mean(axis=1)
    return sr, x / np.abs(x).max()


def first_long_note(x, sr, min_s=30.0):
    """Note-on sample of the first held note longer than min_s (= pass 1).
    The silence threshold is 1 % of peak: the reference notes before pass 1
    sit close together and a lower threshold bridges them into one 'note'."""
    hop = 480
    n = len(x) // hop
    rms = np.sqrt((x[:n * hop].reshape(n, hop) ** 2).mean(1))
    on = rms > 1e-2 * np.abs(x).max()
    i = 0
    while i < n:
        if on[i]:
            j = i
            while j < n and on[j]:
                j += 1
            if (j - i) * hop / sr > min_s:
                return i * hop
            i = j
        i += 1
    raise SystemExit('no pass-1 note found')


def harmonics_at(x, sr, a, k, span=0.15, K=4):
    """Mean complex harmonics h1..H around knob k (absolute-phase coherent)."""
    P = sr / F0
    L = int(round(K * P))
    idx = np.arange(L)
    w = np.hanning(L)
    E = np.exp(-2j * np.pi * np.outer(np.arange(1, H + 1), idx) * F0 / sr) * w
    tc = T0 + k * (T1 - T0)
    s0 = a + int(max(0.05, tc - span / 2) * sr)
    starts = np.arange(s0, s0 + int(span * sr) - L + 1, int(round(K * P)))
    X = np.stack([x[s:s + L] for s in starts])
    C = X @ E.T * 2 / w.sum()
    C *= np.exp(-2j * np.pi * np.outer(starts, np.arange(1, H + 1)) * F0 / sr)
    return C.mean(0)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--dir', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    lines = []
    for name, fn in WAVES:
        sr, x = load(os.path.join(a.dir, fn))
        on = first_long_note(x, sr)
        rows = [harmonics_at(x, sr, on, k) for k in KNOBS]
        lines.append(f'// {fn}: pass-1 note-on at {on / sr:.3f} s')
        lines.append(f'inline constexpr float k{name}Re[{len(KNOBS)}][{H}] = {{')
        for r in rows:
            lines.append('    { ' + ', '.join(f'{v:.6e}f' for v in r.real) + ' },')
        lines.append('};')
        lines.append(f'inline constexpr float k{name}Im[{len(KNOBS)}][{H}] = {{')
        for r in rows:
            lines.append('    { ' + ', '.join(f'{v:.6e}f' for v in r.imag) + ' },')
        lines.append('};')
    with open(a.out, 'w', newline='\r\n') as f:
        f.write('// ' + '=' * 77 + '\n')
        f.write('// JpOsc1Fixtures.h — GENERATED by jt8000-params/tools/jp_osc_fixtures.py.\n')
        f.write('// Do not edit.  JE-8086 (JP-8000) OSC1 SHAPE, complex harmonics h1..h40 at\n')
        f.write('// 9 calibrated Ctrl1 positions (pass 1, Ctrl2 = 0), f0 130.8132 Hz.\n')
        f.write('// Host-test data only (never linked into firmware).\n')
        f.write('// ' + '=' * 77 + '\n#pragma once\n\nnamespace JT { namespace JpOsc1Fixtures {\n\n')
        f.write(f'inline constexpr int kNumKnobs = {len(KNOBS)};\n')
        f.write(f'inline constexpr int kNumHarm  = {H};\n')
        f.write('inline constexpr float kKnob[kNumKnobs] = { '
                + ', '.join(f'{k:.3f}f' for k in KNOBS) + ' };\n\n')
        f.write('\n'.join(lines) + '\n\n} } // namespace JT::JpOsc1Fixtures\n')
    print(f'wrote {a.out}')


if __name__ == '__main__':
    main()
