// =============================================================================
// test_wavetable_reader.cpp — proofs for OscCore's ONE table reader and the
// measured JP-8000 OSC1 SHAPE waves
// =============================================================================
// ARB (AKWF, 1 frame × 1 level) and the measured JvTRI morph (33 frames × 7
// band-limited levels, since 2026-10-22) share renderTable().  These tests pin:
//   * SHAPE reaches EVERY frame — min, centre and max read frames 0, 16 and 32
//     sample-exact (no 5..95 % pulse clamp on the morph);
//   * a full SHAPE sweep is click-free (block-rate morph, no steps) — also
//     for the closed-form JvSAW and JTRIM;
//   * the level selector / polyBLEP keep a high note alias-free;
//   * OscSection attaches the flash set when JvTRI is selected;
//   * JvSAW, JvTRI and JTRIM match the JE-8086 MEASUREMENT (fixtures in
//     JpOsc1Fixtures.h, generated by jt8000-params/tools/jp_osc_fixtures.py).
// ARB byte-identity across the merge is proved separately by a cmp of rendered
// output before/after (all FM/sync feature combinations) — see delivery note.
// =============================================================================
#include "doctest.h"

#include <cmath>
#include <vector>

#include "core/dsp/OscCore.h"
#include "core/OscSection.h"
#include "core/WavetableLib.h"
